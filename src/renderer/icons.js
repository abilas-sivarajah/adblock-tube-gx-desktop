export function icon(name) {
  const svg = document.createElementNS('http://www.w3.org/2000/svg', 'svg');
  svg.setAttribute('viewBox', '0 0 24 24');
  svg.setAttribute('class', 'i');
  svg.setAttribute('aria-hidden', 'true');
  const path = document.createElementNS('http://www.w3.org/2000/svg', 'path');
  path.setAttribute('d', PATHS[name] ?? '');
  svg.appendChild(path);
  return svg;
}

/** Symbol eines Knopfs setzen (ersetzt nur das SVG, Text/Badges bleiben). */
export function setIcon(el, name) {
  if (!el || el.dataset.current === name) return;
  el.dataset.current = name;
  el.querySelector('svg.i')?.remove();
  el.prepend(icon(name));
}

/** Alle Elemente mit data-icon="…" einmalig füllen. */
export function hydrateIcons(root = document) {
  for (const el of root.querySelectorAll('[data-icon]')) setIcon(el, el.dataset.icon);
}
